# ---------- Сборка ----------

def build() -> Path:
    doc = Document()

    # Базовые настройки страницы
    for section in doc.sections:
        section.left_margin = Cm(2)
        section.right_margin = Cm(2)
        section.top_margin = Cm(2)
        section.bottom_margin = Cm(2)

    # Стиль по умолчанию
    style = doc.styles["Normal"]
    style.font.name = "Calibri"
    style.font.size = Pt(11)

    cover(doc)
    chapter_intro(doc)
    chapter_terms(doc)
    chapter_broker(doc)
    chapter_risk(doc)
    chapter_tech(doc)
    chapter_strategy(doc)
    chapter_journal(doc)
    chapter_tools(doc)
    chapter_roadmap(doc)
    chapter_resources(doc)
    chapter_final(doc)

    doc.save(OUT)
    return OUT


if __name__ == "__main__":
    print("Собираю Word-документ...")
    path = build()
    size_kb = path.stat().st_size // 1024
    print(f"✓ Готово: {path}")
    print(f"  Размер: {size_kb} KB")
    sys.exit(0)
