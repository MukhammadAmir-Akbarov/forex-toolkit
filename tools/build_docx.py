# ---------- Стили ----------

def set_cell_bg(cell, color_hex: str) -> None:
    """Заливка ячейки таблицы."""
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:fill"), color_hex)
    tc_pr.append(shd)


def add_page_break(doc: Document) -> None:
    p = doc.add_paragraph()
    run = p.add_run()
    run.add_break(WD_BREAK.PAGE)


def h1(doc: Document, text: str, page_break_before: bool = True) -> None:
    if page_break_before:
        add_page_break(doc)
    p = doc.add_heading(text, level=1)
    for run in p.runs:
        run.font.color.rgb = RGBColor(0x1E, 0x40, 0xAF)


def h2(doc: Document, text: str) -> None:
    p = doc.add_heading(text, level=2)
    for run in p.runs:
        run.font.color.rgb = RGBColor(0x1F, 0x29, 0x37)


def h3(doc: Document, text: str) -> None:
    p = doc.add_heading(text, level=3)
    for run in p.runs:
        run.font.color.rgb = RGBColor(0x37, 0x41, 0x51)


def para(doc: Document, text: str, bold: bool = False, italic: bool = False,
         size: int = 11) -> None:
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic


def callout(doc: Document, text: str, color: str = "FEF3C7",
            title: str = "⚠️ ВАЖНО") -> None:
    """Жёлтая/красная плашка с предупреждением."""
    table = doc.add_table(rows=1, cols=1)
    cell = table.rows[0].cells[0]
    set_cell_bg(cell, color)
    cell.paragraphs[0].text = ""
    p = cell.paragraphs[0]
    title_run = p.add_run(title + "\n")
    title_run.bold = True
    title_run.font.size = Pt(12)
    text_run = p.add_run(text)
    text_run.font.size = Pt(11)
    doc.add_paragraph()


def bullet(doc: Document, text: str, level: int = 0) -> None:
    p = doc.add_paragraph(text, style="List Bullet")
    if level > 0:
        p.paragraph_format.left_indent = Cm(0.75 * (level + 1))


def numbered(doc: Document, text: str) -> None:
    doc.add_paragraph(text, style="List Number")


def code_block(doc: Document, code: str) -> None:
    """Моноширинный текст как «код» в сером блоке."""
    table = doc.add_table(rows=1, cols=1)
    cell = table.rows[0].cells[0]
    set_cell_bg(cell, "F3F4F6")
    cell.text = ""
    for line in code.split("\n"):
        p = cell.add_paragraph()
        run = p.add_run(line if line else " ")
        run.font.name = "Menlo"
        run.font.size = Pt(9)
        # Восточные шрифты
        r = run._element
        rPr = r.get_or_add_rPr()
        rFonts = OxmlElement("w:rFonts")
        rFonts.set(qn("w:ascii"), "Menlo")
        rFonts.set(qn("w:hAnsi"), "Menlo")
        rPr.append(rFonts)
    # удалить первый пустой параграф
    first = cell.paragraphs[0]
    first._element.getparent().remove(first._element)
    doc.add_paragraph()


def make_table(doc: Document, header: list[str], rows: list[list[str]],
               col_widths: list[float] | None = None) -> None:
    table = doc.add_table(rows=1 + len(rows), cols=len(header))
    table.style = "Light Grid Accent 1"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER

    for j, h in enumerate(header):
        cell = table.rows[0].cells[j]
        cell.text = ""
        set_cell_bg(cell, "1E40AF")
        p = cell.paragraphs[0]
        run = p.add_run(h)
        run.bold = True
        run.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF)
        run.font.size = Pt(10)

    for i, row in enumerate(rows, start=1):
        for j, val in enumerate(row):
            cell = table.rows[i].cells[j]
            cell.text = ""
            p = cell.paragraphs[0]
            run = p.add_run(str(val))
            run.font.size = Pt(10)

    if col_widths:
        for row in table.rows:
            for j, w in enumerate(col_widths):
                row.cells[j].width = Cm(w)

    doc.add_paragraph()


def image(doc: Document, name: str, caption: str = "",
          width_cm: float = 16) -> None:
    path = IMG / name
    if not path.exists():
        para(doc, f"[картинка не найдена: {name}]", italic=True)
        return
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.add_run().add_picture(str(path), width=Cm(width_cm))
    if caption:
        cap = doc.add_paragraph()
        cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run = cap.add_run("Рис. " + caption)
        run.italic = True
        run.font.size = Pt(9)
        run.font.color.rgb = RGBColor(0x6B, 0x72, 0x80)


