def category_analysis(scores: dict) -> str:
    weak_categories = []
    for cat, score in scores.items():
        cat_max = sum(
            max(o[1] for o in q.options) for q in QUESTIONS if q.category == cat
        )
        if cat_max > 0 and score / cat_max < WEAK_RATIO:
            weak_categories.append((cat, score, cat_max))

    if not weak_categories:
        return "✅ Сильные стороны во всех категориях."

    out = "⚠️  СЛАБЫЕ ЗОНЫ (требуют работы):\n"
    names = {
        "finance": "💰 Финансы",
        "time": "⏰ Время и обучение",
        "psychology": "🧠 Психология",
        "character": "🎭 Характер",
        "experience": "📚 Опыт",
        "health": "❤️ Здоровье",
        "relationships": "👨‍👩‍👧 Отношения",
        "motivation": "🎯 Мотивация",
        "warnings": "🚩 Предупреждения",
    }
    for cat, s, m in weak_categories:
        out += f"  {names.get(cat, cat)}: {s}/{m}\n"
    return out


def simulate_answer(q: Question, profile: str, rng: random.Random) -> int:
    """Возвращает балл для симулированного профиля.

    profile:
      'ideal'      — лучший ответ каждый раз
      'realistic'  — средний реалистичный новичок
      'risky'      — много красных флагов
      'random'     — случайный выбор
    """
    if profile == "ideal":
        return max(o[1] for o in q.options)
    if profile == "risky":
        return min(o[1] for o in q.options)
    if profile == "random":
        return rng.choice(q.options)[1]
    # realistic — взвешенный выбор к середине
    sorted_opts = sorted(q.options, key=lambda o: o[1], reverse=True)
    # 50% второй вариант, 30% первый, 20% третий-четвёртый
    r = rng.random()
    if r < 0.30:
        return sorted_opts[0][1]
    elif r < 0.80:
        return sorted_opts[min(1, len(sorted_opts) - 1)][1]
    elif r < 0.95 and len(sorted_opts) >= 3:
        return sorted_opts[2][1]
    else:
        return sorted_opts[-1][1]


def main() -> int:
    parser = argparse.ArgumentParser(description="Risk profile questionnaire")
    parser.add_argument(
        "--simulate",
        choices=["ideal", "realistic", "risky", "random"],
        help="Демо-прогон без интерактивных вопросов",
    )
    parser.add_argument("--seed", type=int, default=42, help="Seed для симуляции")
    args = parser.parse_args()

    print("=" * 70)
    print("  PERSONAL RISK PROFILE — оценка готовности к forex")
    print("=" * 70)

    if args.simulate:
        print(f"\n🧪 DEMO MODE: симуляция профиля '{args.simulate}'")
        print("   (для интерактивного режима запусти без --simulate)\n")
        rng = random.Random(args.seed)
    else:
        print(
            "\n30 вопросов, около 10 минут. Отвечай ЧЕСТНО — это для тебя самого.\n"
            "Никто не увидит результат."
        )
        input("\nНажми Enter, чтобы начать...")

    scores = {}
    total = 0
    for i, q in enumerate(QUESTIONS, 1):
        if args.simulate:
            points = simulate_answer(q, args.simulate, rng)
        else:
            points = ask_question(q, i, len(QUESTIONS))
        total += points
        scores.setdefault(q.category, 0)
        scores[q.category] += points

    max_score = sum(max(o[1] for o in q.options) for q in QUESTIONS)

    print("\n\n" + "=" * 70)
    print("  ТВОЙ РЕЗУЛЬТАТ")
    print("=" * 70)
    print(f"\nОбщий счёт: {total} из {max_score} ({total / max_score * 100:.1f}%)")
    print()
    print(interpret_score(total, max_score))
    print()
    print(category_analysis(scores))
    print()
    print("=" * 70)
    print("Рекомендации:")
    print("  • Сохрани этот результат")
    print("  • Через 6 месяцев пройди тест снова — посмотри прогресс")
    print("  • Слабые зоны — приоритет для работы")
    print()
    return 0


if __name__ == "__main__":
    sys.exit(main())
