def ask_question(q: Question, index: int, total: int) -> int:
    print(f"\n[{index}/{total}] {q.text}\n")
    for i, (label, _) in enumerate(q.options, 1):
        print(f"  {i}) {label}")
    while True:
        try:
            choice = input("\nТвой выбор (1-{}): ".format(len(q.options))).strip()
            num = int(choice)
            if 1 <= num <= len(q.options):
                return q.options[num - 1][1]
        except (ValueError, EOFError):
            print("Введи число 1-{}".format(len(q.options)))
            continue
        print("Неверный выбор, попробуй снова")


